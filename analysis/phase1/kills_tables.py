#!/usr/bin/env python3
# kills_tables.py: the report's tables of the final runs, from analysis/results/kills/*.csv, to tables.md. Nothing is typed by hand.
import collections, csv, math, statistics as st

OUT = "analysis/results/kills"
CASES = [("one", "One node"), ("twoA", "Two, first killed returns first"), ("twoB", "Two, last killed returns first"),
         ("twoC", "Two at the same moment"), ("twoD", "Second killed just after first returns"),
         ("allA", "All three, back together"), ("allB", "All three, back one at a time")]
T95 = {2: 12.71, 3: 4.30, 4: 3.18, 5: 2.78}


def read(name):
    try:
        return list(csv.DictReader(open(f"{OUT}/{name}.csv")))
    except FileNotFoundError:
        return []


def num(row, key, default=0.0):
    value = row.get(key, "")
    return float(value) if value not in ("", None, "None") else default


def mean_ci(values):
    if len(values) < 2:
        return f"{values[0]:,.0f}" if values else "-"
    return f"{st.mean(values):,.0f} ± {T95.get(len(values), 2.0) * st.stdev(values) / math.sqrt(len(values)):,.0f}"


def span(values, fmt="{:,.0f}"):
    if not values:
        return "-"
    return fmt.format(min(values)) if min(values) == max(values) else f"{fmt.format(min(values))}-{fmt.format(max(values))}"


def table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    out += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(out) + "\n"


def nodes(row, key):
    return [num(row, f"{key}_{n}") for n in (1, 2, 3) if row.get(f"{key}_{n}") not in ("", None)]


def main():
    runs, steps, phases, others = read("runs"), read("steps"), read("phases"), read("others")
    out = ["<!-- Generated by analysis/phase1/kills_tables.py. Do not edit. -->\n"]
    commits = sorted({r["commit"] for r in runs + others})
    out.append(f"Commits in these tables: {', '.join('`' + c + '`' for c in commits)}.\n")
    labels = {"300": "300/s, with planning", "10000": "10,000/s, with planning", "15000": "15,000/s, no simulated planning", "20000": "20,000/s, no simulated planning"}
    out.append("### Totals\n")
    def lost(r, kind):
        v = nodes(r, f"answered_{kind}_not_in_file")
        return int(min(v)) if len(v) == 3 else 0
    def one_file(r, kind):
        v = nodes(r, f"answered_{kind}_not_in_file")
        return int(sum(x - lost(r, kind) for x in v))
    out.append(table(["Runs", "Sent", "Answered", "Of those, provisional", "Gave up", "Unaccounted", "Checkpoints compared", "Digest mismatches"],
                     [[len(runs), f"{sum(int(num(r, 'sent')) for r in runs):,}", f"{sum(int(num(r, 'answered')) for r in runs):,}", f"{sum(int(num(r, 'provisional')) for r in runs):,}",
                       f"{sum(int(num(r, 'gave_up')) for r in runs):,}", sum(int(num(r, 'unaccounted')) for r in runs), f"{sum(int(num(r, 'checkpoints')) for r in runs):,}", sum(int(num(r, 'digest_mismatches')) for r in runs)]]))
    out.append("### Every answer checked against each node's own file\n")
    bad = [r for r in runs if any(lost(r, k) or one_file(r, k) for k in ("committed", "provisional"))]
    out.append(f"In {len(runs) - len(bad)} of {len(runs)} runs every answer is in all three files. The others:\n")
    out.append(table(["Case", "Load", "Run", "Kills and returns, seconds", "Answered", "Committed answers in no node's file", "Provisional answers in no node's file", "Missing from one node's file only, committed and provisional", "Resets", "Final digests differ"],
                     [[r["case"], r["rate"], r["run"], r["steps"], f"{int(num(r, 'answered')):,}", lost(r, "committed"), lost(r, "provisional"), one_file(r, "committed") + one_file(r, "provisional"), sum(1 for n in (1, 2, 3) if "resets=1" in r.get(f"file_stats_{n}", "")), r.get("final_digests_differ", "")] for r in bad]))
    gone = sum(lost(r, "committed") + lost(r, "provisional") for r in runs)
    answered = sum(num(r, "answered") for r in runs)
    out.append(f"In all: {gone:,} of {answered:,.0f} answers are in no node's file, {100 * gone / max(1, answered):.4f}%.\n")
    for rate in sorted({r["rate"] for r in runs}, key=int):
        rows = []
        for key, name in CASES:
            v = [r for r in runs if r["rate"] == rate and r["case"] == key]
            if not v:
                continue
            per_s = [num(r, "answered") / max(1, num(r, "sent")) * int(rate) for r in v]
            rows.append([name, len(v), mean_ci(per_s), span([100 * num(r, "answered") / max(1, num(r, "sent")) for r in v], "{:.1f}%"), span([num(r, "gave_up") for r in v]),
                         sum(int(num(r, "unaccounted")) for r in v), sum(int(num(r, "digest_mismatches")) for r in v), span([num(r, "p50_ms") for r in v]), span([num(r, "p99_ms") / 1000 for r in v], "{:.1f} s"),
                         span([num(r, "longest_no_answer_s") for r in v], "{:.1f} s"), span([num(r, "longest_no_commit_s") for r in v], "{:.1f} s"), ", ".join(sorted({r["commit"] for r in v}))])
        out.append(f"### Kills at {labels.get(rate, rate)}\n")
        out.append(table(["Kill case", "Runs", "Equivalent answers/s", "Answered", "Gave up, per run", "Unaccounted", "Digest mismatches", "p50 ms", "p99", "Longest with no answer", "Longest with no commit", "Commit"], rows))
    out.append("### Answers by how many nodes were up\n")
    rows = []
    for rate in sorted({p["rate"] for p in phases}, key=int):
        for up in ("3", "2", "1", "0"):
            v = [p for p in phases if p["rate"] == rate and p["nodes_up"] == up and num(p, "to_s") - num(p, "from_s") >= 3]
            if v:
                rows.append([labels.get(rate, rate), up, len(v), f"{st.mean(num(p, 'answers_per_s') for p in v):,.0f}", f"{st.mean(num(p, 'committed_per_s') for p in v):,.0f}", f"{st.mean(num(p, 'provisional_per_s') for p in v):,.0f}", span([num(p, "p50_ms") for p in v]), span([num(p, "p99_ms") / 1000 for p in v], "{:.1f} s")])
    out.append(table(["Load", "Nodes up", "Stretches", "Answers/s", "Committed/s", "Provisional/s", "p50 ms", "p99"], rows))
    out.append("Stretches shorter than 3 s are left out. The last stretch after all nodes are back includes the time to work through what built up.\n")
    out.append("### Coming back, seconds after the restart\n")
    rows = []
    for rate in sorted({s["rate"] for s in steps}, key=int):
        back = [s for s in steps if s["rate"] == rate and s["what"] == "back"]
        get = lambda prefix: [num(s, k) for s in back for k in s if k.startswith(prefix) and s[k] not in ("", None)]
        rows.append([labels.get(rate, rate), span(get("rebuilt_s_"), "{:.1f}"), span(get("reconnect_"), "{:.2f}"), span(get("tcp_"), "{:.0f}"), span(get("member_again_s_"), "{:.1f}"), span(get("serving_again_s_"), "{:.1f}"), span([num(s, "first_commit_s") for s in back if s.get("first_commit_s")], "{:.1f}")])
    out.append(table(["Load", "Rebuilt from its own file", "A peer's TCP connection back (`peer_reconnected`)", "Seen in `ss`, 1 s steps", "Member again", "Serving again", "First committed answer"], rows))
    out.append("### CPU, memory, network and queues in the kill runs\n")
    rows = []
    for rate in sorted({r["rate"] for r in runs}, key=int):
        v = [r for r in runs if r["rate"] == rate]
        all_of = lambda key: [x for r in v for x in nodes(r, key)]
        rows.append([labels.get(rate, rate), f"{st.mean(all_of('cores_mean')):.1f}", f"{max(all_of('cores_max')):.1f}", f"{max(all_of('max_rss_mb')):,.0f}", f"{st.mean(all_of('net_mb_per_s_mean')):.1f}", f"{max(all_of('queued_max')):,.0f}", f"{max(all_of('running_max')):,.0f}", f"{sum(int(num(r, 'retries_skipped')) for r in v):,}"])
    out.append(table(["Load", "Cores, mean per node", "Cores, highest", "Memory, highest MB", "Network MB/s per node", "Queued, highest", "Planning, highest", "Retries the budget skipped"], rows))
    def other_table(title, chosen):
        chosen = sorted(chosen, key=lambda o: (o["experiment"], o["cell"].rjust(10), int(o["run"])))
        if not chosen:
            return
        rows = [[o["experiment"], o["cell"], o["run"], o["users"] if o["users"] != "0" else "-", f"{int(num(o, 'sent')):,}", f"{int(num(o, 'answered')):,}", f"{int(num(o, 'answered_per_s')):,}", f"{int(num(o, 'provisional')):,}", f"{int(num(o, 'gave_up')):,}", int(num(o, "unaccounted")), int(num(o, "digest_mismatches")), f"{num(o, 'p50_ms'):,.0f}", f"{num(o, 'p95_ms'):,.0f}", f"{num(o, 'p99_ms'):,.0f}", o.get("first_try_pct", ""), f"{st.mean(nodes(o, 'cores_mean') or [0]):.1f}", f"{max(nodes(o, 'max_rss_mb') or [0]):,.0f}", f"{st.mean(nodes(o, 'net_mb_per_s_mean') or [0]):.1f}", f"{max(nodes(o, 'queued_max') or [0]):,.0f}", o["commit"]] for o in chosen]
        out.append(f"### {title}\n")
        out.append(table(["Test", "Cell", "Run", "Users", "Sent", "Answered", "Answers/s", "Provisional", "Gave up", "Unaccounted", "Digest mismatches", "p50 ms", "p95 ms", "p99 ms", "First try %", "Cores per node", "Memory MB", "Network MB/s", "Queued, most", "Commit"], rows))
    other_table("Speed with no failures, on the final build, midday", [o for o in others if o["experiment"] in ("final0", "final1")])
    other_table("The guide's T1, T2 and T4", [o for o in others if o["experiment"] in ("power", "oneleft", "draw")])
    other_table("Flat out, the spike, and users per PC", [o for o in others if o["experiment"] in ("stress", "users")])
    t2 = [o for o in others if o["experiment"] == "oneleft"]
    if t2:
        out.append("### T2's provisional answers\n")
        out.append(table(["Run", "Provisional answers", "Changed in the end", "Responder taken", "Lost first commit", "Final digests differ", "Commit"], [[o["run"], f"{int(num(o, 'provisional')):,}", f"{int(num(o, 'conflicts_total')):,}", f"{int(num(o, 'conflicts_responder_taken')):,}", f"{int(num(o, 'conflicts_lost_first_commit')):,}", o.get("final_digests_differ", ""), o["commit"]] for o in t2]))
    open(f"{OUT}/tables.md", "w").write("\n".join(out))
    # Where it stalls, overnight, from the series' own per-run figures.
    night = list(csv.DictReader(open("analysis/results/exp8h/runs.csv")))
    rows = []
    for name, label in (("s0", "Almost no planning"), ("s1", "About 3.9 ms of planning")):
        cells = collections.defaultdict(list)
        for row in night:
            if row.get("experiment") == name:
                cells[int(row["cell"])].append(row)
        for rate in sorted(cells):
            v = cells[rate]
            answered = [num(r, "answered_per_s") for r in v]
            sent, done = sum(num(r, "sent") for r in v), sum(num(r, "done") for r in v)
            rows.append([label, f"{rate:,}", len(v), f"{st.mean(answered):,.0f}", span(answered), f"{100 * done / max(1, sent):.2f}%", f"{int(sum(num(r, 'gave_up') for r in v)):,}", span([num(r, "p50_ms") for r in v]), span([num(r, "p99_ms") / 1000 for r in v], "{:.2f} s"), f"{st.mean(num(r, 'cpu_cores_per_node') for r in v):.1f}"])
    open(f"{OUT}/stall.md", "w").write(table(["Work per report", "Offered/s", "Runs", "Answers/s", "Lowest-highest run", "Reports answered", "Gave up, all runs", "p50 ms", "p99", "Cores per node"], rows))
    print(f"wrote {OUT}/tables.md: {len(runs)} kill runs, {len(others)} others")


if __name__ == "__main__":
    main()
